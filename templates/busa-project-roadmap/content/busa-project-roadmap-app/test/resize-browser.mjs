import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE });
try {
 const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 const url = (process.env.ROADMAP_PREVIEW_URL || 'http://127.0.0.1:3108')+'/?demo=1';
 await page.goto(url);
 const handle=page.getByRole('separator', {name:'Resize project and milestone column'});
 await handle.waitFor();
 await mkdir('coverage/resize',{recursive:true});
 await page.screenshot({path:'coverage/resize/default.png'});
 const box=await handle.boundingBox();
 await page.mouse.move(box.x+box.width/2,box.y+25);
 await page.mouse.down();
 await page.mouse.move(box.x+box.width/2+250,box.y+25,{steps:12});
 await page.mouse.up();
 assert.equal(await handle.getAttribute('aria-valuenow'),'520');
 assert.ok(await page.locator('.row-label').evaluateAll(rows=>rows.every(r=>Math.abs(r.getBoundingClientRect().width-520)<1)));
 // Every label that previously fit remains readable, and all rows share the same divider.
 assert.ok(await page.locator('.row-label.child .text-button').evaluateAll(items=>items.every(el=>el.scrollWidth<=el.clientWidth)));
 await page.screenshot({path:'coverage/resize/wide.png'});
 await page.reload();await handle.waitFor();
 assert.equal(await handle.getAttribute('aria-valuenow'),'520');
 await page.getByRole('button',{name:'Collapse all',exact:true}).click();
 assert.equal(await handle.getAttribute('aria-valuenow'),'520');
 await handle.focus();await page.keyboard.press('ArrowLeft');
 assert.equal(await handle.getAttribute('aria-valuenow'),'500');
 await page.keyboard.press('End');assert.equal(await handle.getAttribute('aria-valuenow'),'640');
 await page.keyboard.press('Home');assert.equal(await handle.getAttribute('aria-valuenow'),'180');
 await page.keyboard.press('Enter');assert.equal(await handle.getAttribute('aria-valuenow'),'270');
 await page.getByRole('button',{name:'Expand all',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.waitForFunction(()=>document.querySelector('.roadmap-divider').getAttribute('aria-valuenow')==='220');
 assert.equal(await handle.getAttribute('aria-valuenow'),'220');
 const mobileBox=await handle.boundingBox();
 const cdp=await page.context().newCDPSession(page);
 const point={x:mobileBox.x+6,y:mobileBox.y+24};
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:point.x+80,y:point.y}]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 assert.equal(await handle.getAttribute('aria-valuenow'),'300');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'coverage/resize/mobile.png'});
 await page.locator('.timeline').evaluate(el=>el.scrollLeft=100);
 const scrolled=await handle.boundingBox();
 await page.mouse.move(scrolled.x+6,scrolled.y+24);await page.mouse.down();
 await page.mouse.move(scrolled.x+26,scrolled.y+24);await page.mouse.up();
 assert.equal(await handle.getAttribute('aria-valuenow'),'320');
 assert.deepEqual(errors,[]);
 console.log('Resize verified: drag, aligned rows, readable labels, reload/collapse persistence, keyboard/reset, touch, horizontal scroll, mobile overflow.');
} finally {await browser.close();}
